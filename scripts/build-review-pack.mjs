/* Builds the review pack a qualified tradesperson marks up.

   The trade content cannot be signed off from inside this repo — that is the
   whole point of item 8. What the repo CAN do is stop the review being a
   scavenger hunt through a 700-line JS file: this emits one Markdown document
   per trade, question by question, with the codes the answer is held to and a
   verdict column to fill in.

   Run: node scripts/build-review-pack.mjs
   Writes: docs/review/<trade>-content-review.md
*/
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import vm from "node:vm";

const ctx = { console };
ctx.window = ctx;
vm.createContext(ctx);
vm.runInContext(readFileSync("trades.js", "utf8"), ctx);
const pack = JSON.parse(readFileSync("tracks/welding/practice.json", "utf8"));
const T = ctx.Trades;

mkdirSync("docs/review", { recursive: true });

const HEAD = (trade) => `# ${trade.name} — content review

**For review by a qualified ${trade.name.replace(/^Professional /, "").toLowerCase()}.**
Generated by \`scripts/build-review-pack.mjs\`. Do not edit by hand — edit
\`trades.js\` and regenerate.

## What this is, and what it is not

BE Mastery teaches **spoken English for the workplace**. These are the questions a
learner is asked in each workshop and the model answer they are shown and hear.
The app scores whether the learner *said* the required points, not whether the
technique is correct.

So the question for you is not "is this the best way to do the job". It is:

1. **Would a ${trade.name.replace(/^Professional /, "").toLowerCase()} actually say this?** Wrong register, dated
   terms, or wording nobody uses on site.
2. **Is anything stated as fact that is wrong or unsafe?** Especially isolation,
   permits, confined space and rigging.
3. **Is anything region-specific presented as universal?**

Mark each row **OK**, **REWORD**, or **WRONG**, and add a note. Anything marked
WRONG comes out of the app before the next release.

**Codes this trade is held to:** ${trade.codes.join(" · ")}

---
`;

for (const trade of T.all()) {
  if (trade.id === "welder") continue;   // the pack itself is the welder's content
  let md = HEAD(trade);
  let n = 0;
  for (const moduleId of trade.modules) {
    const sc = pack.simulations.find(x => Number(x.regulatory?.moduleId) === moduleId);
    if (!sc) continue;
    const own = T.scenarioFor(trade, moduleId);
    md += `\n## Workshop ${moduleId} — ${own?.title || sc.title}\n\n`;
    const codes = T.codesFor(trade, moduleId);
    if (codes?.length) md += `*Assessed against:* ${codes.join(" · ")}\n\n`;
    for (const key of ["open", "t0", "t1", "t2", "t3"]) {
      const q = T.questionFor(trade, moduleId, key);
      if (!q) continue;
      n++;
      md += `### ${moduleId}.${key}\n\n`;
      md += `**Asked:** ${q.ask}\n\n`;
      md += `**Model answer the learner shadows:**\n\n> ${q.model}\n\n`;
      if (q.vocab?.length) md += `**Terms scored:** ${q.vocab.join(", ")}\n\n`;
      md += `| Verdict | Note |\n|---|---|\n|  |  |\n\n`;
    }
  }
  md += `\n---\n\n**${n} answers in this pack.** Reviewed by: ______________________  Date: ____________\n`;
  const out = `docs/review/${trade.id}-content-review.md`;
  writeFileSync(out, md);
  console.log(`${out} — ${n} answers`);
}
