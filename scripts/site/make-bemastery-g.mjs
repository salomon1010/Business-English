/* ───────────────────────────────────────────────────────────────────────────
   site/bemastery-g/index.html  —  BUILT, NOT HAND-WRITTEN.

   One app, one page (owner, 15 Oct 2026): /bemastery-g/ sells General English
   and nothing else, /bemastery-w/ sells Welding and nothing else.

   /bemastery/ stays exactly as it is and is NOT generated by this script: it is
   the support URL registered in both live store submissions and it has sixteen
   translations. This script forks it and cuts the Welding half out, so when
   that page changes the General English page is re-made from it rather than
   drifting:

       node scripts/site/make-bemastery-g.mjs

   Every cut below asserts that it matched. If an edit upstream renames a
   section or moves a card, the build FAILS instead of quietly shipping Welding
   content on the General English page — the one thing this page must not do.
   The last guard is a sweep for the word itself.

   Assets (css/, js/, img/) are NOT copied: they are the shared design system
   and are referenced at their absolute /bemastery/ paths. Only the content is
   per-app.
   ─────────────────────────────────────────────────────────────────────────── */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../../site/bemastery/index.html");
const OUT = resolve(here, "../../site/bemastery-g/index.html");

let h = readFileSync(SRC, "utf8");
const steps = [];

/* `what` is for the failure message: a cut that no longer matches is a build
   error, never a silent no-op. */
const cut = (what, from, to) => {
  const i = h.indexOf(from);
  if (i < 0) throw new Error(`cut "${what}": the opening text is gone — ${from.slice(0, 60)}`);
  const j = to === undefined ? i + from.length : h.indexOf(to, i);
  if (j < 0) throw new Error(`cut "${what}": the closing text is gone — ${to.slice(0, 60)}`);
  const end = to === undefined ? j : j + to.length;
  h = h.slice(0, i) + h.slice(end);
  steps.push(`cut  ${what} (${end - i} chars)`);
};
const sub = (what, from, to, count = 1) => {
  const parts = h.split(from);
  if (parts.length - 1 !== count) throw new Error(`replace "${what}": matched ${parts.length - 1}×, expected ${count}×`);
  h = parts.join(to);
  steps.push(`edit ${what} (${count}×)`);
};
/* Like cut(), but stops BEFORE the closing text instead of swallowing it. */
const cutBefore = (what, from, to) => {
  const i = h.indexOf(from), j = h.indexOf(to, i);
  if (i < 0) throw new Error(`cutBefore "${what}": the opening text is gone — ${from.slice(0, 60)}`);
  if (j < 0) throw new Error(`cutBefore "${what}": the closing text is gone — ${to.slice(0, 60)}`);
  h = h.slice(0, i) + h.slice(j);
  steps.push(`cut  ${what} (${j - i} chars)`);
};
/* A whole <section id="…">…</section>, found by its id and closed on the
   comment that opens the next one, so nested </section> cannot fool it. */
const cutSection = (id, nextMarker) => {
  const open = h.indexOf(`<section class="section" id="${id}">`);
  if (open < 0) throw new Error(`section #${id} is gone`);
  const next = h.indexOf(nextMarker, open);
  if (next < 0) throw new Error(`section #${id}: the marker that follows it is gone — ${nextMarker.slice(0, 50)}`);
  h = h.slice(0, open) + h.slice(next);
  steps.push(`cut  section #${id} (${next - open} chars)`);
};

/* ── 1. the page's own address ─────────────────────────────────────────── */
sub("canonical", '<link rel="canonical" href="https://lomonec.com/bemastery/">',
                 '<link rel="canonical" href="https://lomonec.com/bemastery-g/">');
sub("og:url", '<meta property="og:url" content="https://lomonec.com/bemastery/">',
              '<meta property="og:url" content="https://lomonec.com/bemastery-g/">');
sub("title", "<title>BE Mastery — AI English Speaking Practice</title>",
             "<title>BE Mastery — English speaking practice</title>");

/* ── 2. no translations of THIS page exist yet, so it claims none ──────── */
cut("hreflang alternates", "<!-- i18n:alternates -->", "<!-- /i18n:alternates -->");
cut("language picker", "<!-- i18n:lang -->", "<!-- /i18n:lang -->");

/* ── 3. nothing to strip from the store metadata any more: /bemastery/ now
       carries Google Play alone, because the iPhone listing is still in review
       and app id 6817207864 answers 404 (19 Oct 2026). This page inherits that
       as it stands, and only its own address changes. The assertion below is
       what tells us if an Apple URL is ever put back upstream. */
if (/apps\.apple\.com/.test(h)) throw new Error("the source page carries an Apple URL again — check that the listing is live before letting it through");
/* the browser link under the stores points at THIS app's own web app
   (docs/WEB-STANDALONE.md): one programme per address, like the store app. */
sub("the web app link", 'href="https://app.lomonec.com/bemastery/">use it in your browser',
                        'href="https://app.lomonec.com/general-english/">use it in your browser');
sub("JSON-LD url", '"url":"https://lomonec.com/bemastery/"', '"url":"https://lomonec.com/bemastery-g/"');

/* ── 4. the page is one directory further out, so relative asset paths are
       re-pointed at the shared folder, and data-root sends the links app.js
       renders (team.html, blog/) back there too. */
/* app.js: data-page names the page (absent = "home", so "#x" links stay
   scrolls) and data-root is the way back to the folder the shared pages and
   scripts live in, which is one level out from here. */
sub("body attributes", "<body>", '<body data-root="/bemastery/">');
const before = h;
h = h.replace(/(src|href|poster)="(img|css|js)\//g, '$1="/bemastery/$2/');
if (h === before) throw new Error("no relative asset path was re-pointed");
steps.push(`edit asset paths → /bemastery/ (${(h.match(/"\/bemastery\/(img|css|js)\//g) || []).length} refs)`);

/* ── 5. the shared nav and footer carry a Welding entry. js/config.js is read
       by /bemastery/ and its sixteen translations, so it is not edited: this
       page drops the entries after it loads and before app.js renders them
       (config.js is synchronous, app.js is deferred). */
sub("nav/footer override", '<script src="/bemastery/js/analytics.js',
  `<!-- One app per page: the Welding entries are dropped from the shared nav
     and footer here rather than in js/config.js, which /bemastery/ and its
     translations also read. "General English" pointed at #paths, the
     two-programmes section, which this page does not have. -->
<script>
(function () {
  var C = window.BEM; if (!C) return;
  var keep = function (list) {
    return (list || []).filter(function (x) {
      return !/welding/i.test(x.href || "") && !/welding/i.test(x.label || "") && x.href !== "#paths";
    });
  };
  C.nav = keep(C.nav);
  (C.footer || []).forEach(function (g) { g.links = keep(g.links); });
})();
</script>
<script src="/bemastery/js/analytics.js`);

/* ── 6. the drifting feature strip names the other app twice (the track is
       printed twice so it can loop seamlessly). */
sub("marquee Welding English", '<span class="mq-i"><i aria-hidden="true"></i>Welding English</span><span class="mq-i"><i aria-hidden="true"></i>10 trades</span>', "", 2);

/* ── 7. What's new (hidden, but its text is still in the page) ─────────── */
cut("What's new: Welding studio card", '<article class="new-card glass" data-reveal data-reveal-delay="0"><span class="new-date">Sep 2026</span><h3>Welding English studio</h3>', '</article>');
sub("What's new: game hubs", "English Mastery and Welding Mastery: eight games each, a daily mission and skill badges.",
                            "English Mastery: eight games, a daily mission and skill badges.");

/* ── 8. widgets ────────────────────────────────────────────────────────── */
sub("widgets: the two-widget line", "<b>Small, medium and large,</b> plus the lock screen on iPhone. A General English and a Welding English widget, side by side if you study both.",
                                    "<b>Small, medium and large,</b> plus the lock screen on iPhone. Your streak, today's step and your Recommendations, without opening the app.");
cut("widgets: the both-programmes shot", '<figure class="shot" data-reveal data-reveal-delay="160"><div class="shot-phone"><img src="/bemastery/img/widgets/home-both.webp"', "</figure>");

/* ── 9. the game hubs: this page shows English Mastery only ───────────── */
sub("games: one hub, not each", "Each programme has its own game hub, built from its own lessons. Eight short games turn what you are learning into answers you can give out loud.",
                                "The game hub is built from your own lessons. Eight short games turn what you are learning into answers you can give out loud.");
cut("games: the English Mastery heading, now the only one",
    '<h3 class="shots-h" data-reveal>English Mastery · General English</h3>\n    ', undefined);
cut("games: the Welding Mastery heading and its shots",
    '    <h3 class="shots-h" data-reveal>Welding Mastery · Welding English</h3>\n',
    '</div>\n');
sub("games: the section comment", `     The two game hubs: English Mastery (General English) and Welding Mastery
     (Welding English). Shots: scripts/store-art/shoot-games.mjs. -->`,
  `     English Mastery, the General English game hub.
     Shots: scripts/store-art/shoot-games.mjs. -->`);
cut("games: the Welding Mastery bullet", '<li><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m5 13 4 4L19 7"/></svg><span><b>Welding Mastery, for Welding English:</b>', "</li>");
sub("games: rounds in each programme", "Free: five challenge rounds a day in each programme — a wrong answer never costs a round",
                                       "Free: five challenge rounds a day — a wrong answer never costs a round");

/* ── 10. who it's for: the trades card belongs to the other app ────────── */
cut("who: the skilled-trades card", '<div class="who-card glass" data-reveal data-reveal-delay="180"><b>Skilled trades</b>', "</div>");

/* ── 11. the two sections that are about having two programmes ─────────── */
/* #paths ("Two programmes") and #welding sit next to each other, so one cut
   takes both, their comment headers included, and stops at the comment that
   opens Pricing. */
cutBefore("the two-programmes and Welding sections", "<!-- ── 09 TWO PATHS", "<!-- ── 10 PRICING");
if (h.includes('id="paths"') || h.includes('id="welding"')) throw new Error("a cut section is still there");
steps.push("chk  #paths and #welding are gone");

/* ── 12. the FAQ answer that sent people to the other app ──────────────── */
cut("faq: is there a programme for my trade", '<details class="faq-q glass"><summary>Is there a programme for my trade?', "</details>");

/* ── 13. the section numbers are printed, so they are renumbered ───────── */
let n = 0;
h = h.replace(/<span class="n">\d\d<\/span>/g, () => `<span class="n">${String(++n).padStart(2, "0")}</span>`);
if (n < 10) throw new Error(`only ${n} numbered sections were found`);
steps.push(`edit renumbered ${n} sections 01–${String(n).padStart(2, "0")}`);

/* ── the guard ─────────────────────────────────────────────────────────── */
/* What a visitor can read: comments and scripts are stripped, because the
   override above must name the entries it drops. */
const visible = h.replace(/<!--[\s\S]*?-->/g, "").replace(/<script[\s\S]*?<\/script>/g, "");
const left = (visible.match(/welding/gi) || []).length;
if (left) {
  const where = [...visible.matchAll(/[\s\S]{0,80}welding[\s\S]{0,80}/gi)].map(m => "    …" + m[0].replace(/\s+/g, " ") + "…").join("\n");
  throw new Error(`the General English page still mentions the other app ${left}×:\n${where}`);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, h);
console.log(steps.map(s => "  " + s).join("\n"));
console.log(`\n  wrote site/bemastery-g/index.html — ${(h.length / 1024).toFixed(1)} KB, no mention of the other app`);
